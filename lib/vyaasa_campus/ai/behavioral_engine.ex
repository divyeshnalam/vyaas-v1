  defp response_for(state) do
    {reply, spoken_reply} = last_assistant_text(state.messages)
    active = state.active_scenario || %{}

    # During the probe phase the "current question" the candidate answers is the
    # follow-up probe, not the scenario.
    scenario_question =
      if state.phase == :probing, do: state.probe_question, else: active["question"]

    %{
      "session_id" => state.session_id,
      "reply" => reply,
      "spoken_reply" => spoken_reply,
      "scenario_options" => state.current_options,
      "scenario_question" => scenario_question,
      "is_followup" => state.phase == :probing,
      "scenarios_count" => length(state.scenarios_completed),
      "phase" => Atom.to_string(state.phase),
      "interview_finished" => state.phase == :finished,
      "report" => state.report
    }
  end

  defp last_assistant_text(messages) do
    messages
    |> Enum.reverse()
    |> Enum.find(&(&1.role == "assistant"))
    |> case do
      nil -> {"", nil}
      %{content: c, spoken: s} -> {c, s}
      %{content: c} -> {c, nil}
    end
  end

