  defp gibberish_report(name, student_id, completed, quality) do
    reason =
      "The candidate did not provide a substantive answer to any scenario " <>
        "(e.g. responses were empty, a single token, or under #{@min_words_per_answer} words). " <>
        "There is no evidence on which to assess this competency."

    ratings =
      @competency_keys
      |> Enum.map(fn k -> {k, %{"score" => 0, "reasoning" => reason}} end)
      |> Enum.into(%{})

    avg_words = Float.round(quality.avg_words_per_scenario, 0) |> trunc()

    report = %{
      "candidate_name" => name,
      "student_id" => student_id,
      "overall_score" => 0,
      "ratings" => ratings,
      "summary" =>
        "Assessment could not be evaluated: the candidate's responses to the scenarios " <>
          "were empty or non-substantive (average #{avg_words} words per answer, well below the " <>
          "minimum required for evaluation). We recommend the candidate retake the assessment " <>
          "and answer each scenario in the STAR format with a clear situation, task, specific " <>
          "actions they took, and the outcome.",
      "strengths" => [],
      "areas_for_development" => [
        "Provide substantive answers that engage with each scenario.",
        "Use the STAR structure: Situation, Task, Action, Result.",
        "Describe specific actions taken, using 'I' rather than 'we'.",
        "Aim for at least 80–120 words per scenario."
      ],
      "completed_scenarios" => completed,
      "raw_text" => ""
    }

    Map.put(report, "raw_text", format_report_text(report))
  end

