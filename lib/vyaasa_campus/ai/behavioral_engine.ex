  defp format_report_text(report) do
    ratings = Map.get(report, "ratings", %{})

    competency_lines =
      @competency_keys
      |> Enum.map_join("\n", fn k ->
        r = Map.get(ratings, k, %{})
        label = Map.get(@competency_labels, k)
        score = Map.get(r, "score", 0)
        "  • #{String.pad_trailing(label, 32)}  #{pad_score(score)}/100"
      end)

    reasoning_lines =
      @competency_keys
      |> Enum.map_join("\n", fn k ->
        r = Map.get(ratings, k, %{})
        label = Map.get(@competency_labels, k)
        "  • #{label}: #{Map.get(r, "reasoning", "")}"
      end)

    strengths = format_list(Map.get(report, "strengths", []))
    development = format_list(Map.get(report, "areas_for_development", []))

    """
    ================================================================================
    COMPREHENSIVE BEHAVIORAL ASSESSMENT REPORT
    ================================================================================

    CANDIDATE: #{Map.get(report, "candidate_name", "N/A")}

    COMPETENCY RATINGS (Scale: 0–100)
    ────────────────────────────────────────────────────────────────────────────────
    #{competency_lines}

    OVERALL SCORE:                    #{Map.get(report, "overall_score", 0)}/100
    ────────────────────────────────────────────────────────────────────────────────
    REASONING
    ────────────────────────────────────────────────────────────────────────────────
    #{reasoning_lines}

    ────────────────────────────────────────────────────────────────────────────────
    EXECUTIVE SUMMARY
    ────────────────────────────────────────────────────────────────────────────────
    #{Map.get(report, "summary", "")}

    ────────────────────────────────────────────────────────────────────────────────
    KEY STRENGTHS
    ────────────────────────────────────────────────────────────────────────────────
    #{strengths}

    ────────────────────────────────────────────────────────────────────────────────
    DEVELOPMENT AREAS
    ────────────────────────────────────────────────────────────────────────────────
    #{development}

    Thank you for participating in this behavioral assessment.
    """
  end

  defp pad_score(n) when is_integer(n), do: n |> Integer.to_string() |> String.pad_leading(3)
  defp pad_score(_), do: "  0"

  defp format_list([]), do: "(none)"

  defp format_list(items) when is_list(items) do
    items
    |> Enum.with_index(1)
    |> Enum.map_join("\n", fn {item, i} -> "#{i}. #{item}" end)
  end

  defp format_list(_), do: ""

